// Command notices regenerates THIRD-PARTY-NOTICES.txt, the license and
// notice texts of the Go modules that the released binaries compile in.
// The binaries are built for the release platforms only: the server on
// Linux x86 with the build tags the Dockerfile builds it with, and the
// terminal interface on macOS and Linux, on ARM and x86, as GoReleaser
// does.
//
// The module set comes from the go tool, the license names from
// go-licenses (pinned in mise.toml, so run this through mise). A module
// whose license is missing or outside the allowlist below stops the
// generation, so a dependency that conflicts with Garner's MIT license
// cannot ship unnoticed; the allowlist covers the permissive licenses
// that let Garner redistribute them. License texts are read from the
// module cache: every LICENSE, COPYING or NOTICE file at a module's
// root, plus every license file go-licenses found elsewhere in it.
//
// With --check the file is only compared against a fresh generation, as
// mise run check does. Run mise run notices to regenerate.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	mainModule = "github.com/trucke/garner"
	notices    = "THIRD-PARTY-NOTICES.txt"

	// go-licenses prints one line per library and license with this
	// template: the library's module name and version, the license it
	// identified and where the text lives.
	reportTemplate = `{{range .}}{{printf "%s|%s|%s|%s\n" .Name .Version .LicenseName .LicensePath}}{{end}}`

	header = `Garner's third-party notices

The programs Garner releases, the server (garnerd) and the terminal
interface (garner), are built with the Go modules listed below, in the
versions that Garner's go.mod pins. Each module's license text follows,
with any NOTICE file it carries: those licenses let Garner, under the
MIT license in the LICENSE file next to this one, ship the binaries
with them, and they ask that these texts travel with the binaries.
FFprobe, the image's other program, is not a Go module and is covered
by the LGPL text shipped in the image.

This file is generated by tools/notices from the modules the release
platforms compile in; do not edit it. When a dependency changed, run
mise run notices, read its summary, and commit the result.

`
)

// allowedLicenses holds the licenses that may ship with Garner under the
// MIT license, as go-licenses names them. Anything else is flagged for
// review before it can reach a release.
var allowedLicenses = map[string]bool{
	"Apache-2.0":   true,
	"BSD-2-Clause": true,
	"BSD-3-Clause": true,
	"ISC":          true,
	"MIT":          true,
	"MIT-0":        true,
	"Unlicense":    true,
	"Zlib":         true,
}

// build is one binary the releases ship: its package and the platform
// and build tags it is compiled with.
type build struct {
	pkg  string
	os   string
	arch string
	tags string // the terminal interface is built without tags
}

func main() {
	check := len(os.Args) == 2 && os.Args[1] == "--check"
	if !check && len(os.Args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: go run ./tools/notices [--check]")
		os.Exit(2)
	}

	builds := []build{
		{pkg: "./cmd/garnerd", os: "linux", arch: "amd64", tags: dockerfileTags()},
		{pkg: "./cmd/garner", os: "darwin", arch: "amd64"},
		{pkg: "./cmd/garner", os: "darwin", arch: "arm64"},
		{pkg: "./cmd/garner", os: "linux", arch: "amd64"},
		{pkg: "./cmd/garner", os: "linux", arch: "arm64"},
	}

	modules := map[string]*module{}
	for _, b := range builds {
		listModules(b, modules)
		licenseNames(b, modules)
	}
	for _, m := range modules {
		rootLicenseFiles(m)
		if len(m.names) == 0 {
			fail("%s %s compiled in, but go-licenses found no license for it; find it and decide whether Garner may ship it", m.path, m.version)
		}
	}

	paths := make([]string, 0, len(modules))
	for path := range modules {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	var out bytes.Buffer
	out.WriteString(header)
	for _, path := range paths {
		render(&out, modules[path])
	}

	if check {
		want, err := os.ReadFile(notices)
		if err != nil {
			fail("%s cannot be read: %v", notices, err)
		}
		if !bytes.Equal(out.Bytes(), want) {
			fail("%s is not current; run mise run notices and commit the result", notices)
		}
	} else if err := os.WriteFile(notices, out.Bytes(), 0o644); err != nil {
		fail("%s cannot be written: %v", notices, err)
	}

	// After a regeneration, the list is what to read before committing;
	// a passing check only says so.
	if !check {
		for _, path := range paths {
			m := modules[path]
			fmt.Printf("%s %s %s (%s)\n", m.path, m.version,
				strings.Join(sorted(m.names), ", "), strings.Join(sorted(m.files), ", "))
		}
	}
	fmt.Printf("%d modules, all licenses on the allowlist\n", len(paths))
}

// module is one Go module compiled into the released binaries: its
// version, the folder it is cached in, and the license names and files
// that go with it.
type module struct {
	path, version, dir string
	names              map[string]bool // license names go-licenses found
	files              map[string]bool // license files, relative to dir
}

// listModules adds the modules that a build compiles in, from the go
// tool, which also knows where each module is cached.
func listModules(b build, modules map[string]*module) {
	const template = `{{if and .Module (ne .Module.Path "` + mainModule + `")}}` +
		`{{printf "%s %s %s\n" .Module.Path .Module.Version .Module.Dir}}{{end}}`
	cmd := exec.Command("go", "list", "-deps", "-f", template, b.pkg)
	cmd.Env = buildEnv(b)
	out, err := cmd.Output()
	if err != nil {
		fail("%s: %v", b.pkg, err)
	}
	seen := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		if line == "" {
			continue
		}
		path, rest, _ := strings.Cut(line, " ")
		version, dir, ok := strings.Cut(rest, " ")
		if !ok || seen[path] {
			if !ok {
				fail("cannot read the go tool's line for %s: %q", b.pkg, line)
			}
			continue // many packages share a module
		}
		seen[path] = true
		if m, ok := modules[path]; ok {
			if m.version != version {
				fail("%s is compiled in as %s and as %s", path, m.version, version)
			}
			continue
		}
		modules[path] = &module{path: path, version: version, dir: dir,
			names: map[string]bool{}, files: map[string]bool{}}
	}
}

// licenseNames runs go-licenses for a build and records each module's
// license names and files, failing on a license outside the allowlist.
func licenseNames(b build, modules map[string]*module) {
	tmpl, err := os.CreateTemp("", "notices-template-*")
	if err != nil {
		fail("%s: %v", b.pkg, err)
	}
	defer os.Remove(tmpl.Name())
	if _, err := tmpl.WriteString(reportTemplate); err != nil {
		fail("%s: %v", b.pkg, err)
	}
	if err := tmpl.Close(); err != nil {
		fail("%s: %v", b.pkg, err)
	}

	cmd := exec.Command("go-licenses", "report", b.pkg, "--template", tmpl.Name())
	cmd.Env = buildEnv(b)
	out, err := cmd.Output()
	if err != nil {
		fail("%s: %v", b.pkg, err)
	}
	for _, line := range strings.Split(string(out), "\n") {
		if line == "" {
			continue
		}
		name, rest, _ := strings.Cut(line, "|")
		version, rest, _ := strings.Cut(rest, "|")
		license, file, _ := strings.Cut(rest, "|")
		if version == "Unknown" || license == "" {
			// "Unknown" is the main module, whose LICENSE ships as-is;
			// an empty license means go-licenses found none, which the
			// check after all builds reports per module.
			continue
		}
		m := moduleFor(modules, name, file)
		if !allowedLicenses[license] {
			fail("%s %s ships under %s, which is not on the allowlist; review it before releasing", m.path, m.version, license)
		}
		m.names[license] = true
		m.files[strings.TrimPrefix(strings.TrimPrefix(file, m.dir), "/")] = true
	}
}

// moduleFor finds the module a go-licenses library belongs to, by its
// cache folder. A license file outside every known module means the go
// tool and go-licenses disagree; that must be looked at, not guessed.
func moduleFor(modules map[string]*module, name, file string) *module {
	for _, m := range modules {
		if file == m.dir || strings.HasPrefix(file, m.dir+string(filepath.Separator)) {
			return m
		}
	}
	fail("go-licenses reports %s for %s, outside the modules the go tool knows", file, name)
	return nil
}

// rootLicenseFiles adds every LICENSE, COPYING or NOTICE file at a
// module's root to its license files.
func rootLicenseFiles(m *module) {
	entries, err := os.ReadDir(m.dir)
	if err != nil {
		fail("%s %s: %v", m.path, m.version, err)
	}
	for _, entry := range entries {
		name := strings.ToLower(entry.Name())
		if entry.Type().IsRegular() &&
			(strings.HasPrefix(name, "license") || strings.HasPrefix(name, "copying") || strings.HasPrefix(name, "notice")) {
			m.files[entry.Name()] = true
		}
	}
	if len(m.files) == 0 {
		fail("%s %s has no license file in its module cache folder; find its license and decide whether Garner may ship it", m.path, m.version)
	}
}

func render(out *bytes.Buffer, m *module) {
	fmt.Fprintf(out, "===============================================================================\n%s %s\nLicense: %s\nLicense files: %s\n",
		m.path, m.version, strings.Join(sorted(m.names), ", "), strings.Join(sorted(m.files), ", "))
	for _, file := range sorted(m.files) {
		text, err := os.ReadFile(filepath.Join(m.dir, file))
		if err != nil {
			fail("%s %s: %v", m.path, m.version, err)
		}
		fmt.Fprintf(out, "\n----- %s -----\n%s\n", file, strings.TrimRight(string(text), "\n"))
	}
	out.WriteByte('\n')
}

// buildEnv runs the go tool and go-licenses as the release builds the
// binary, regardless of how this generator was run.
func buildEnv(b build) []string {
	env := make([]string, 0, len(os.Environ()))
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "CGO_ENABLED=") || strings.HasPrefix(kv, "GOOS=") ||
			strings.HasPrefix(kv, "GOARCH=") || strings.HasPrefix(kv, "GOFLAGS=") {
			continue
		}
		env = append(env, kv)
	}
	env = append(env, "CGO_ENABLED=0", "GOOS="+b.os, "GOARCH="+b.arch)
	if b.tags != "" {
		env = append(env, "GOFLAGS=-tags="+b.tags)
	}
	return env
}

// dockerfileTags reads the build tags the image builds Garner's server
// with, so the notices cannot drift from what actually ships.
func dockerfileTags() string {
	data, err := os.ReadFile("Dockerfile")
	if err != nil {
		fail("the Dockerfile cannot be read: %v", err)
	}
	tags := regexp.MustCompile(`go build -tags (\S+)`).FindSubmatch(data)
	if tags == nil {
		fail("the Dockerfile names no build tags for garnerd")
	}
	return string(tags[1])
}

func sorted(set map[string]bool) []string {
	all := make([]string, 0, len(set))
	for s := range set {
		all = append(all, s)
	}
	sort.Strings(all)
	return all
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "✗ "+format+"\n", args...)
	os.Exit(1)
}
