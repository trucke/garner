// Command devstack runs Garner's local development stack: SABnzbd, Prowlarr
// and Jellyfin in a Podman pod on this machine, configured entirely by this
// program. Data lives in ~/garner-dev; the services listen on 127.0.0.1 only.
//
//	devstack up      create or start the stack and bring its setup up to date
//	devstack down    stop the stack, keeping its data
//	devstack reset   delete the stack and its data, then build it again
//	devstack status  show what runs
//
// Run it through `mise run devstack <command>`, which supplies the external
// credentials from Infisical: USENET_USERNAME, USENET_PASSWORD,
// INDEXER_API_KEY and SECOND_INDEXER_API_KEY.
package main

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/BurntSushi/toml"
)

const (
	pod = "garner-dev"
	// Same versions as production; pinned by digest.
	sabImage      = "docker.io/linuxserver/sabnzbd:5.1.3@sha256:382f9bd4e3f6df2abf7bcc92edada0c5bd4d4ff26eb5416f257ac54989464fa1"
	prowlarrImage = "docker.io/linuxserver/prowlarr:2.6.5@sha256:f9151e5bc1025c6d0a630d503210cdcb6bb55a7cc098562609d96a408d838902"
	jellyfinImage = "docker.io/jellyfin/jellyfin:12.1.20260915-010956@sha256:78d3ea1207d1322471fcac39a614f004f2ccf7e878f95ab2977d752f07e4dd7e"

	sabURL      = "http://127.0.0.1:8080"
	prowlarrURL = "http://127.0.0.1:9696"
	jellyfinURL = "http://127.0.0.1:8096"

	// generatedMark starts the garner.toml this program writes, so it can
	// tell its own file from one written by hand.
	generatedMark = "# Generated by tools/devstack (mise run devstack up); changes are overwritten."
)

func main() {
	cmd := ""
	if len(os.Args) > 1 {
		cmd = os.Args[1]
	}
	var err error
	switch cmd {
	case "up":
		err = up()
	case "down":
		err = run("pod", "stop", pod)
	case "reset":
		err = reset()
	case "status":
		err = status()
	default:
		fmt.Fprintln(os.Stderr, "usage: devstack up|down|reset|status")
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "devstack:", err)
		os.Exit(1)
	}
}

// root is the stack's data folder. It must lie in the home folder: Podman's
// virtual machine on macOS can only mount folders from there.
func root() string {
	home, err := os.UserHomeDir()
	if err != nil {
		panic(err)
	}
	return filepath.Join(home, "garner-dev")
}

func path(parts ...string) string { return filepath.Join(append([]string{root()}, parts...)...) }

// credentials are the external accounts the stack uses.
type credentials struct {
	usenetUser, usenetPassword, firstIndexer, secondIndexer string
}

func readCredentials() (credentials, error) {
	c := credentials{
		usenetUser: os.Getenv("USENET_USERNAME"), usenetPassword: os.Getenv("USENET_PASSWORD"),
		firstIndexer: os.Getenv("INDEXER_API_KEY"), secondIndexer: os.Getenv("SECOND_INDEXER_API_KEY"),
	}
	required := map[string]string{"USENET_USERNAME": c.usenetUser, "USENET_PASSWORD": c.usenetPassword,
		"INDEXER_API_KEY": c.firstIndexer, "SECOND_INDEXER_API_KEY": c.secondIndexer}
	var missing []string
	for name, v := range required {
		if v = strings.TrimSpace(v); v == "" || v == "REPLACE_ME" {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		return c, fmt.Errorf("set %s in Infisical (project media-manager, env dev) and run through `mise run devstack`", strings.Join(missing, ", "))
	}
	return c, nil
}

func up() error {
	creds, err := readCredentials()
	if err != nil {
		return err
	}
	for _, dir := range []string{
		"config/sabnzbd", "config/prowlarr", "config/jellyfin", "cache/jellyfin", "secrets", "garner",
		"media/usenet/incomplete", "media/usenet/complete", "media/library/tv", "media/library/anime",
	} {
		if err := os.MkdirAll(path(dir), 0o755); err != nil {
			return err
		}
	}
	if err := os.Chmod(path("secrets"), 0o700); err != nil {
		return err
	}
	if err := ensurePod(); err != nil {
		return err
	}
	step("SABnzbd")
	sabKey, err := setupSABnzbd(creds)
	if err != nil {
		return fmt.Errorf("SABnzbd: %w", err)
	}
	step("Prowlarr")
	prowlarrKey, err := setupProwlarr(creds)
	if err != nil {
		return fmt.Errorf("Prowlarr: %w", err)
	}
	step("Jellyfin")
	jellyfinKey, err := setupJellyfin()
	if err != nil {
		return fmt.Errorf("Jellyfin: %w", err)
	}
	for name, key := range map[string]string{"sabnzbd_api_key": sabKey, "prowlarr_api_key": prowlarrKey, "jellyfin_api_key": jellyfinKey} {
		if err := writeSecret(name, key); err != nil {
			return err
		}
	}
	step("Garner")
	if err := writeGarnerConfig(); err != nil {
		return err
	}
	fmt.Printf(`
The dev stack is ready. Data: %s
  SABnzbd   %s
  Prowlarr  %s
  Jellyfin  %s  (user garner-dev, password in secrets/jellyfin_admin_password)
Run Garner against it with: mise run dev
`, root(), sabURL, prowlarrURL, jellyfinURL)
	return nil
}

// ensurePod creates the pod and its containers, replaces a container whose
// image is outdated, and starts everything. The services share the pod's
// network, so SABnzbd reaches Prowlarr's download links at 127.0.0.1.
func ensurePod() error {
	if exec.Command("podman", "pod", "exists", pod).Run() != nil {
		step("creating the pod")
		if err := run("pod", "create", "--name", pod, "--label", "garner.devstack=1",
			"-p", "127.0.0.1:8080:8080", "-p", "127.0.0.1:9696:9696", "-p", "127.0.0.1:8096:8096"); err != nil {
			return err
		}
	}
	lsio := []string{"-e", "PUID=1000", "-e", "PGID=1000", "-e", "TZ=Europe/Vienna"}
	containers := []struct {
		name, image string
		args        []string
	}{
		{pod + "-sabnzbd", sabImage, append(lsio, "-v", path("config/sabnzbd")+":/config", "-v", path("media")+":/data")},
		{pod + "-prowlarr", prowlarrImage, append(lsio, "-v", path("config/prowlarr")+":/config")},
		{pod + "-jellyfin", jellyfinImage, []string{"-e", "TZ=Europe/Vienna",
			"-v", path("config/jellyfin") + ":/config", "-v", path("cache/jellyfin") + ":/cache",
			"-v", path("media/library") + ":/data/library:ro"}},
	}
	for _, c := range containers {
		// Podman drops the tag of a digest-pinned image, so compare digests.
		if out, err := output("container", "inspect", "--format", "{{.ImageDigest}}", c.name); err == nil {
			if strings.TrimSpace(out) == c.image[strings.LastIndex(c.image, "@")+1:] {
				continue
			}
			step("replacing " + c.name + " with the pinned image")
			if err := run("rm", "-f", c.name); err != nil {
				return err
			}
		}
		step("creating " + c.name)
		args := append([]string{"create", "--pod", pod, "--name", c.name, "--label", "garner.devstack=1"}, c.args...)
		if err := run(append(args, c.image)...); err != nil {
			return err
		}
	}
	return run("pod", "start", pod)
}

func reset() error {
	if _, err := os.Stat(path("garner", "garner.sock")); err == nil {
		return errors.New("Garner seems to run against the stack (garner/garner.sock exists); stop it first")
	}
	fmt.Printf("This deletes the dev stack and everything in %s: downloads, library, settings and Garner's dev database.\nType reset to continue: ", root())
	answer, _ := bufio.NewReader(os.Stdin).ReadString('\n')
	if strings.TrimSpace(answer) != "reset" {
		return errors.New("cancelled")
	}
	if exec.Command("podman", "pod", "exists", pod).Run() == nil {
		if err := run("pod", "rm", "-f", pod); err != nil {
			return err
		}
	}
	if err := os.RemoveAll(root()); err != nil {
		return err
	}
	return up()
}

func status() error {
	if exec.Command("podman", "pod", "exists", pod).Run() != nil {
		fmt.Println("The dev stack does not exist; run `mise run devstack up`.")
		return nil
	}
	out, err := output("ps", "--pod", "--filter", "pod="+pod, "--format", "{{.Names}}\t{{.Status}}")
	if err != nil {
		return err
	}
	fmt.Print(out)
	return nil
}

func writeSecret(name, value string) error {
	return os.WriteFile(path("secrets", name), []byte(value+"\n"), 0o600)
}

func readSecret(name string) string {
	b, _ := os.ReadFile(path("secrets", name))
	return strings.TrimSpace(string(b))
}

// writeGarnerConfig writes garner.toml in the current folder (the Garner
// repository) for the stack, unless that file was written by hand.
func writeGarnerConfig() error {
	const file = "garner.toml"
	if old, err := os.ReadFile(file); err == nil && !bytes.HasPrefix(old, []byte(generatedMark)) {
		fmt.Printf("  %s exists and was not written by devstack; leaving it alone.\n", file)
		return nil
	}
	type service struct {
		URL      string            `toml:"url"`
		Category string            `toml:"category,omitempty"`
		Paths    map[string]string `toml:"paths,omitempty"`
	}
	cfg := struct {
		DataDir string `toml:"data_dir"`
		Server  struct {
			Listen string `toml:"listen"`
		} `toml:"server"`
		Library struct {
			TV    string `toml:"tv"`
			Anime string `toml:"anime"`
		} `toml:"library"`
		Prowlarr service `toml:"prowlarr"`
		SABnzbd  service `toml:"sabnzbd"`
		Jellyfin service `toml:"jellyfin"`
	}{DataDir: path("garner")}
	cfg.Server.Listen = "127.0.0.1:7979"
	cfg.Library.TV, cfg.Library.Anime = path("media/library/tv"), path("media/library/anime")
	cfg.Prowlarr = service{URL: prowlarrURL}
	cfg.SABnzbd = service{URL: sabURL, Category: "tv", Paths: map[string]string{"/data/usenet": path("media/usenet")}}
	cfg.Jellyfin = service{URL: jellyfinURL, Paths: map[string]string{"/data/library": path("media/library")}}
	var b bytes.Buffer
	b.WriteString(generatedMark + "\n# Garner against the local dev stack. API keys come from ~/garner-dev/secrets.\n\n")
	if err := toml.NewEncoder(&b).Encode(cfg); err != nil {
		return err
	}
	return os.WriteFile(file, b.Bytes(), 0o644)
}

func run(args ...string) error {
	_, err := output(args...)
	return err
}

// output runs podman. Arguments never carry secrets, so errors may quote them.
func output(args ...string) (string, error) {
	var stderr bytes.Buffer
	cmd := exec.Command("podman", args...)
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("podman %s: %v: %s", strings.Join(args[:min(2, len(args))], " "), err, strings.TrimSpace(stderr.String()))
	}
	return string(out), nil
}

func step(s string) { fmt.Println("·", s) }

// waitFor polls until ready reports true or the time is up.
func waitFor(what string, limit time.Duration, ready func() bool) error {
	deadline := time.Now().Add(limit)
	for !ready() {
		if time.Now().After(deadline) {
			return fmt.Errorf("%s did not happen within %s", what, limit)
		}
		time.Sleep(time.Second)
	}
	return nil
}
